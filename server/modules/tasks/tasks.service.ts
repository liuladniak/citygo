export type Viewer = { role: string | null; email: string | null };

const OPEN_STATUSES = ["open", "in_progress"];
const DISMISS_ROLES = ["admin", "manager"];
const NOW = sql`CURRENT_TIMESTAMP`;

const cleanTitle = (title: string) => title.replace(/^\[auto_\w+\]\s*/, "");

const assignee = alias(employees, "assignee");
const creator = alias(employees, "creator");
const fullName = (e: { firstName: AnyPgColumn; lastName: AnyPgColumn }) => sql<string | null>`${e.firstName} || ' ' || ${e.lastName}`;

const withDetails = {
  ...snakeColumns(tasks),
  assignee_name: fullName(assignee),
  assignee_image: assignee.profileImage,
  creator_name: fullName(creator),
  booking_reference: bookings.bookingReference,
};

const detailedTasks = () =>
  db
    .select(withDetails)
    .from(tasks)
    .leftJoin(assignee, eq(tasks.assignedTo, assignee.id))
    .leftJoin(creator, eq(tasks.createdBy, creator.id))
    .leftJoin(bookings, eq(tasks.bookingId, bookings.id));

const present = (row: Record<string, unknown>) => isoTimestamps(tasks, row);

const urgentFirst = sql`CASE ${tasks.priority} WHEN 'urgent' THEN 1 WHEN 'normal' THEN 2 WHEN 'low' THEN 3 END`;

export async function listTasks(q: ListQuery) {
  const where: (SQL | undefined)[] = [
    q.include_archived ? undefined : isNull(tasks.archivedAt),
    q.status ? eq(tasks.status, q.status) : undefined,
    q.priority ? eq(tasks.priority, q.priority) : undefined,
    q.type ? eq(tasks.type, q.type) : undefined,
    q.assigned_to === undefined
      ? undefined
      : q.include_unassigned
        ? or(eq(tasks.assignedTo, q.assigned_to), isNull(tasks.assignedTo))
        : eq(tasks.assignedTo, q.assigned_to),
  ];

  const query = detailedTasks()
    .where(and(...where))
    .orderBy(
      urgentFirst,
      sql`CASE WHEN ${tasks.assignedTo} IS NULL THEN 1 ELSE 0 END`,
      sql`${tasks.dueDate} ASC NULLS LAST`,
      desc(tasks.createdAt),
      desc(tasks.id),
    );
  return (q.limit ? await query.limit(q.limit) : await query).map(present);
}

const commentRow = {
  ...snakeColumns(taskComments),
  author_name: fullName(employees),
  author_image: employees.profileImage,
};

const commentsOf = (where: SQL) =>
  db
    .select(commentRow)
    .from(taskComments)
    .leftJoin(employees, eq(taskComments.authorId, employees.id))
    .where(where)
    .orderBy(asc(taskComments.createdAt), asc(taskComments.id));

const presentComment = (row: Record<string, unknown>) => isoTimestamps(taskComments, row);

async function loadTask(id: number) {
  const [task] = await detailedTasks().where(eq(tasks.id, id)).limit(1);
  if (!task) throw notFound("Task not found");
  return present(task);
}

export async function getTask(id: number) {
  const [task, comments] = await Promise.all([loadTask(id), commentsOf(eq(taskComments.taskId, id))]);
  return { ...task, comments: comments.map(presentComment) };
}

/** Who did it is always the signed-in person, never something the browser claims. */
const actorId = async (viewer: Viewer) => (await findEmployeeByEmail(db, viewer.email))?.id ?? null;

export async function createTask(body: CreateBody, viewer: Viewer) {
  const [row] = await db
    .insert(tasks)
    .values({
      title: body.title,
      description: body.description,
      type: body.type,
      bookingId: body.booking_id ?? null,
      assignedTo: body.assigned_to ?? null,
      createdBy: await actorId(viewer),
      priority: body.priority,
      dueDate: body.due_date ?? null,
      isAutoGenerated: false,
    })
    .returning({ id: tasks.id });
  return loadTask(row.id);
}

export async function updateTask(id: number, body: UpdateBody, viewer: Viewer) {
  const [task] = await db.select({ completedAt: tasks.completedAt }).from(tasks).where(eq(tasks.id, id)).limit(1);
  if (!task) throw notFound("Task not found");

  const changes: Partial<typeof tasks.$inferInsert> = { updatedAt: NOW as unknown as string };
  if (body.title !== undefined) changes.title = body.title;
  if (body.description !== undefined) changes.description = body.description;
  if (body.priority !== undefined) changes.priority = body.priority;
  if (body.assigned_to !== undefined) changes.assignedTo = body.assigned_to;
  if (body.due_date !== undefined) changes.dueDate = body.due_date;
  if (body.booking_id !== undefined) changes.bookingId = body.booking_id;

  if (body.status !== undefined) {
    changes.status = body.status;
    if (body.status === "done") {
      if (!task.completedAt) {
        changes.completedAt = NOW as unknown as string;
        changes.completedBy = await actorId(viewer);
      }
    } else {
      changes.completedAt = null;
      changes.completedBy = null;
    }
  }

  await db.update(tasks).set(changes).where(eq(tasks.id, id));
  return loadTask(id);
}

/** Tasks are never deleted; cancelling keeps the history. */
export async function cancelTask(id: number) {
  await db.update(tasks).set({ status: "cancelled", updatedAt: NOW as unknown as string }).where(eq(tasks.id, id));
}

export async function addComment(taskId: number, content: string, viewer: Viewer) {
  const [task] = await db.select({ id: tasks.id }).from(tasks).where(eq(tasks.id, taskId)).limit(1);
  if (!task) throw notFound("Task not found");

  const [comment] = await db
    .insert(taskComments)
    .values({ taskId, authorId: await actorId(viewer), content })
    .returning({ id: taskComments.id });
  const [withAuthor] = await commentsOf(eq(taskComments.id, comment.id));
  return presentComment(withAuthor);
}

type Executor = Pick<typeof db, "select">;

/** Sorts ids into ready, unresolved (an auto task whose booking still needs the work) and skipped. Changes nothing. */
async function planClose(executor: Executor, ids: number[]) {
  const closer = alias(employees, "closer");
  const found = await executor
    .select({
      id: tasks.id,
      title: tasks.title,
      status: tasks.status,
      booking_id: tasks.bookingId,
      is_auto_generated: tasks.isAutoGenerated,
      archived_at: tasks.archivedAt,
      closer_name: fullName(closer),
    })
    .from(tasks)
    .leftJoin(closer, eq(tasks.completedBy, closer.id))
    .where(inArray(tasks.id, ids));
  const byId = new Map(found.map((t) => [t.id, t]));

  const open: typeof found = [];
  const skipped: { id: number; title: string; reason: string }[] = [];
  for (const id of ids) {
    const t = byId.get(id);
    if (!t || t.archived_at) {
      skipped.push({ id, title: t ? cleanTitle(t.title) : `Task #${id}`, reason: "no longer active" });
    } else if (!OPEN_STATUSES.includes(t.status)) {
      skipped.push({ id, title: cleanTitle(t.title), reason: t.closer_name ? `already closed by ${t.closer_name}` : "already closed" });
    } else {
      open.push(t);
    }
  }

  const unresolved = await findUnresolved(executor, open);
  return {
    ready: open.filter((t) => !unresolved.has(t.id)).map((t) => t.id),
    unresolved: open
      .filter((t) => unresolved.has(t.id))
      .map((t) => ({ id: t.id, title: cleanTitle(t.title), reason: unresolved.get(t.id) as string })),
    skipped,
  };
}

export const previewClose = (ids: number[]) => planClose(db, ids);

export async function bulkClose({ ids, action, reason }: BulkBody, viewer: Viewer) {
  if (action === "dismiss") {
    if (!viewer.role || !DISMISS_ROLES.includes(viewer.role)) throw forbidden("Only managers can dismiss tasks");
    if (reason.length < 3) throw badRequest("A reason of 3-500 characters is required");
  }

  const actor = await actorId(viewer);

  return db.transaction(async (tx) => {
    if (action === "reopen") {
      const rows = await tx
        .update(tasks)
        .set({ status: "open", completedAt: null, completedBy: null, updatedAt: NOW as unknown as string })
        .where(and(inArray(tasks.id, ids), inArray(tasks.status, ["done", "dismissed"]), isNull(tasks.archivedAt)))
        .returning({ id: tasks.id });
      return { updated: rows.map((r) => r.id), unresolved: [], skipped: [] };
    }

    // Checked again inside the transaction: the earlier preview may be stale.
    const plan = await planClose(tx, ids);
    // An auto task whose work is still missing is never marked done, only dismissed with a reason.
    const targetIds = action === "done" ? plan.ready : [...plan.ready, ...plan.unresolved.map((u) => u.id)];

    let updated: number[] = [];
    if (targetIds.length > 0) {
      const rows = await tx
        .update(tasks)
        .set({
          status: action === "done" ? "done" : "dismissed",
          completedAt: NOW as unknown as string,
          completedBy: actor,
          updatedAt: NOW as unknown as string,
        })
        .where(and(inArray(tasks.id, targetIds), inArray(tasks.status, OPEN_STATUSES)))
        .returning({ id: tasks.id });
      updated = rows.map((r) => r.id);
    }

    if (action === "dismiss" && updated.length > 0) {
      await tx.insert(taskComments).values(updated.map((taskId) => ({ taskId, authorId: actor, content: `Dismissed: ${reason}` })));
    }

    return { updated, unresolved: action === "done" ? plan.unresolved : [], skipped: plan.skipped };
  });
}

