import { afterAll, beforeEach, describe, expect, it, vi } from "vitest";
import { eq } from "drizzle-orm";
import { db, resetDb } from "../test/db.js";
import { makeEmployee, makeTask, makeTour } from "../test/fixtures.js";
import { bookingAssignments, bookingPayments, bookings, tasks } from "../db/drizzle/schema.js";
import { generateAutoTasks } from "./autoTaskGenerator.js";

// 2026-11-22 09:00 in Istanbul.
const NOW = new Date("2026-11-22T06:00:00Z");

beforeEach(async () => {
  await resetDb();
  vi.spyOn(console, "log").mockImplementation(() => {});
});
afterAll(() => vi.restoreAllMocks());

let ref = 0;
async function makeBooking(overrides: Partial<typeof bookings.$inferInsert> = {}) {
  ref += 1;
  const tour = await makeTour();
  const [row] = await db
    .insert(bookings)
    .values({
      tourId: tour.id, tourDate: "2026-11-23", isCustomTour: true, startTime: "09:00:00", endTime: "13:00:00",
      primaryContactName: "Guest", status: "confirmed", source: "website", bookingReference: `BK-J-${ref}`,
      totalPrice: "100.00", meetingPoint: "Hagia Sophia", ...overrides,
    })
    .returning();
  return row;
}
const allTasks = () => db.select().from(tasks).orderBy(tasks.id);

describe("generateAutoTasks", () => {
  it("opens the tasks a booking needs, and nothing twice", async () => {
    const b = await makeBooking({ meetingPoint: null });
    expect(await generateAutoTasks(NOW)).toEqual({ opened: 3, closed: 0 });

    const rows = await allTasks();
    expect(rows.map((t) => t.title).sort()).toEqual([
      `[auto_assign_guide] Assign guide to ${b.bookingReference}`,
      `[auto_collect_payment] Collect €100.00 from ${b.bookingReference}`,
      `[auto_set_meeting_point] Set meeting point for ${b.bookingReference}`,
    ]);
    expect(rows[0]).toMatchObject({ type: "tour", bookingId: b.id, isAutoGenerated: true, status: "open", priority: "urgent", dueDate: "2026-11-23 00:00:00" });

    expect(await generateAutoTasks(NOW)).toEqual({ opened: 0, closed: 0 });
    expect(await allTasks()).toHaveLength(3);
  });

  it("ignores bookings that are not confirmed, are far away, or already started", async () => {
    await makeBooking({ status: "pending" });
    await makeBooking({ status: "cancelled" });
    await makeBooking({ tourDate: "2026-12-30" });
    await makeBooking({ tourDate: "2026-11-22", startTime: "08:00:00" });
    expect(await generateAutoTasks(NOW)).toEqual({ opened: 0, closed: 0 });
  });

  it("uses the time slot's start when the booking has none of its own", async () => {
    // Slot starts 09:00 on 2026-11-25 Istanbul = 72 h away: just inside the guide window.
    const { makeTimeSlot } = await import("../test/fixtures.js");
    const tour = await makeTour();
    const slot = await makeTimeSlot(tour.id, { startTime: "09:00:00", endTime: "13:00:00" });
    await db.insert(bookings).values({
      tourId: tour.id, timeSlotId: slot.id, tourDate: "2026-11-25", primaryContactName: "G", status: "confirmed",
      source: "website", bookingReference: "BK-SLOT", totalPrice: "0", meetingPoint: "x",
    });
    expect(await generateAutoTasks(NOW)).toEqual({ opened: 1, closed: 0 });
  });

  it("closes an auto task once the work is done, and leaves unfinished ones open", async () => {
    const b = await makeBooking({ meetingPoint: null });
    await generateAutoTasks(NOW);

    const guide = await makeEmployee();
    await db.insert(bookingAssignments).values({ bookingId: b.id, guideId: guide.id, role: "lead_guide", status: "active" });
    await db.insert(bookingPayments).values({ bookingId: b.id, amount: "100.00", status: "paid" } as never);

    expect(await generateAutoTasks(NOW)).toEqual({ opened: 0, closed: 2 });
    const byKind = Object.fromEntries((await allTasks()).map((t) => [t.title.match(/auto_\w+/)![0], t]));
    expect(byKind.auto_assign_guide).toMatchObject({ status: "done", completedBy: null });
    expect(byKind.auto_collect_payment.status).toBe("done");
    expect(byKind.auto_set_meeting_point.status).toBe("open");
  });

  it("does not reopen a task that was done or dismissed, and may reopen a cancelled one", async () => {
    const b = await makeBooking();
    await makeTask({ title: "[auto_assign_guide] Assign guide", bookingId: b.id, isAutoGenerated: true, status: "dismissed" });
    await makeTask({ title: "[auto_collect_payment] Collect", bookingId: b.id, isAutoGenerated: true, status: "cancelled" });
    expect(await generateAutoTasks(NOW)).toEqual({ opened: 1, closed: 0 });
    expect((await allTasks()).filter((t) => t.status === "open").map((t) => t.title)[0]).toContain("auto_collect_payment");
  });

  it("opens a review for a custom draft that has waited a day, but not for a fresh one", async () => {
    const stale = await makeBooking({ status: "draft", tourDate: "2027-05-01", createdAt: "2020-01-01 00:00:00" });
    await makeBooking({ status: "draft", tourDate: "2027-05-01" });
    const { makeTimeSlot } = await import("../test/fixtures.js");
    const tour = await makeTour();
    const slot = await makeTimeSlot(tour.id, { startTime: "09:00:00", endTime: "13:00:00" });
    await makeBooking({ status: "draft", tourDate: "2027-05-01", isCustomTour: false, timeSlotId: slot.id, startTime: null, endTime: null, createdAt: "2020-01-01 00:00:00" });
    expect(await generateAutoTasks(NOW)).toEqual({ opened: 1, closed: 0 });
    const [t] = await allTasks();
    expect(t).toMatchObject({ bookingId: stale.id, priority: "normal", dueDate: null });
    expect(t.title).toContain("auto_review_custom");
  });

  it("archives finished tasks from before today, and keeps today's visible", async () => {
    const yesterday = await makeTask({ status: "done", completedAt: "2026-11-20 10:00:00" });
    const today = await makeTask({ status: "done", completedAt: "2026-11-22 05:00:00" });
    const open = await makeTask({ status: "open" });
    await generateAutoTasks(NOW);
    const by = async (id: number) => (await db.select().from(tasks).where(eq(tasks.id, id)))[0];
    expect((await by(yesterday.id)).archivedAt).not.toBeNull();
    expect((await by(today.id)).archivedAt).toBeNull();
    expect((await by(open.id)).archivedAt).toBeNull();
  });
});
