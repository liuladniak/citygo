import { and, eq, gte, inArray, isNull, lte, ne, sql } from "drizzle-orm";
import { db } from "../db/index.js";
import { bookings, companySettings, tasks, tourTimeSlots, tours } from "../db/drizzle/schema.js";
import { autoTaskKind, findUnresolved, loadPaidAndGuides } from "../lib/autoTaskConditions.js";
import { DEFAULT_TIMEZONE, nowInZone, zonedToInstant } from "../lib/clock.js";
import { addDaysToDay } from "../lib/dates.js";
import {
  ASSIGN_GUIDE_WITHIN_HOURS, planBookingTasks, planDraftTasks, type PlannedTask, type UpcomingBooking,
} from "./autoTaskPlan.js";

const NOW = sql`CURRENT_TIMESTAMP`;
const OPEN = ["open", "in_progress"];

async function companyTimezone() {
  const [row] = await db.select({ timezone: companySettings.timezone }).from(companySettings).limit(1);
  return row?.timezone || DEFAULT_TIMEZONE;
}

async function loadUpcoming(today: string): Promise<UpcomingBooking[]> {
  // Three days ahead covers the 72 hour window whatever the start time is.
  const rows = await db
    .select({
      id: bookings.id,
      booking_reference: bookings.bookingReference,
      tour_name: tours.tourName,
      tour_date: bookings.tourDate,
      start_time: sql<string | null>`coalesce(${bookings.startTime}, ${tourTimeSlots.startTime})`,
      total_price: bookings.totalPrice,
      meeting_point: bookings.meetingPoint,
    })
    .from(bookings)
    .leftJoin(tours, eq(bookings.tourId, tours.id))
    .leftJoin(tourTimeSlots, eq(bookings.timeSlotId, tourTimeSlots.id))
    .where(and(eq(bookings.status, "confirmed"), gte(bookings.tourDate, today), lte(bookings.tourDate, addDaysToDay(today, ASSIGN_GUIDE_WITHIN_HOURS / 24))));
  if (rows.length === 0) return [];

  const countsFor = await loadPaidAndGuides(db, rows.map((r) => r.id));
  return rows.map((r) => ({ ...r, ...countsFor(r.id) }));
}

/** "bookingId:kind" for every auto task that is open or done, so none is opened twice. */
async function existingKeys(bookingIds: number[]) {
  if (bookingIds.length === 0) return new Set<string>();
  const rows = await db
    .select({ bookingId: tasks.bookingId, title: tasks.title })
    .from(tasks)
    .where(and(eq(tasks.isAutoGenerated, true), ne(tasks.status, "cancelled"), inArray(tasks.bookingId, bookingIds)));
  return new Set(rows.map((r) => `${r.bookingId}:${autoTaskKind(r.title)}`));
}

const toRow = (t: PlannedTask): typeof tasks.$inferInsert => ({
  title: t.title,
  description: t.description,
  type: "tour",
  bookingId: t.bookingId,
  priority: t.priority,
  dueDate: t.dueDate,
  isAutoGenerated: true,
  status: "open",
});

/**
 * Runs every hour: opens tasks for bookings that need attention, closes auto tasks whose work
 * has been done, and archives old finished tasks. Running it twice in a row changes nothing.
 */
export async function generateAutoTasks(now: Date = new Date()) {
  try {
    const timeZone = await companyTimezone();
    const today = nowInZone(timeZone, now).date;

    const upcoming = await loadUpcoming(today);
    const drafts = await db
      .select({ id: bookings.id, booking_reference: bookings.bookingReference })
      .from(bookings)
      .where(and(eq(bookings.status, "draft"), eq(bookings.isCustomTour, true), sql`${bookings.createdAt} <= now() - interval '24 hours'`));

    const existing = await existingKeys([...upcoming.map((b) => b.id), ...drafts.map((d) => d.id)]);
    const planned = [...planBookingTasks(upcoming, existing, now, timeZone), ...planDraftTasks(drafts, existing)];
    if (planned.length > 0) await db.insert(tasks).values(planned.map(toRow));

    // Work that got done by hand closes its own task.
    const openAuto = await db
      .select({ id: tasks.id, title: tasks.title, booking_id: tasks.bookingId, is_auto_generated: tasks.isAutoGenerated })
      .from(tasks)
      .where(and(eq(tasks.isAutoGenerated, true), inArray(tasks.status, OPEN), isNull(tasks.archivedAt)));
    const stillNeeded = await findUnresolved(db, openAuto);
    const fixedIds = openAuto.filter((t) => autoTaskKind(t.title) && !stillNeeded.has(t.id)).map((t) => t.id);
    if (fixedIds.length > 0) {
      await db
        .update(tasks)
        .set({ status: "done", completedAt: NOW as unknown as string, completedBy: null, updatedAt: NOW as unknown as string })
        .where(and(inArray(tasks.id, fixedIds), inArray(tasks.status, OPEN)));
    }

    // Finished tasks leave the list the day after.
    const startOfToday = zonedToInstant(today, "00:00:00", timeZone).toISOString().replace("T", " ").replace("Z", "");
    await db
      .update(tasks)
      .set({ archivedAt: NOW as unknown as string })
      .where(and(inArray(tasks.status, ["done", "dismissed"]), lte(tasks.completedAt, startOfToday), isNull(tasks.archivedAt)));

    console.log(`[AutoTaskGenerator] Ran at ${now.toISOString()}: opened ${planned.length}, closed ${fixedIds.length}`);
    return { opened: planned.length, closed: fixedIds.length };
  } catch (err) {
    console.error("[AutoTaskGenerator] Error:", err);
    return { opened: 0, closed: 0 };
  }
}

export default generateAutoTasks;
